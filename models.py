from datetime import datetime, timezone
from sqlalchemy import JSON, Column
from sqlmodel import Field, SQLModel

class Movement(SQLModel, table=True):
    name: str = Field(primary_key=True)
    dip_belt: bool = Field(default=False)

class MovementAlias(SQLModel, table=True):
    """A former name of a renamed movement, so data recorded under the old name still finds it.

    Phones can hold sessions recorded before a rename (in progress, or saved offline); when they
    upload, their movement names are looked up here.
    """
    old_name: str = Field(primary_key=True)
    movement_name: str = Field(foreign_key='movement.name')

class ExerciseBase(SQLModel):
    exercise_name: str = Field(index=True, foreign_key='movement.name')
    sets: int = Field(default=3)
    reps: int
    weight: float
    rpe: float | None = None # Optional for exercises logged in a workout session

class ExerciseCreate(ExerciseBase):
    pass

class Exercise(ExerciseBase, table=True):
    id: int | None = Field(default=None, primary_key=True)
    user_id: int = Field(foreign_key='user.id')
    bodyweight: float | None # Only set for movements with dip_belt=True
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    session_id: int | None = Field(default=None, foreign_key='workoutsession.id', index=True)

class ExercisePublic(ExerciseBase):
    id: int
    created_at: datetime

class User(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    email: str = Field(unique=True)
    bodyweight: float = Field(default=70) # In kg
    is_admin: bool = Field(default=False)

class WorkoutDay(SQLModel, table=True):
    """A recurring workout in the user's program, e.g. "Primary Pull".

    slots is a list of {"movements": [str, ...], "sets": int, "reps": int,
    "week_targets": [{"sets": int, "reps": int}, ...] | None,
    "rpe_targets": [float, ...] | None}. The movements in a slot are
    alternatives (e.g. different row variations). week_targets holds sets and
    reps for each week of the cycle when they change from week to week; when
    it is missing or None, sets and reps apply to every week (when present,
    sets and reps equal week 1's). rpe_targets holds one target per week of
    the cycle (days saved by older versions may have a single target for
    every week).
    """
    id: int | None = Field(default=None, primary_key=True)
    user_id: int = Field(foreign_key='user.id', index=True)
    name: str
    weekday: int | None = None # 0 = Monday ... 6 = Sunday
    slots: list[dict] = Field(default_factory=list, sa_column=Column(JSON, nullable=False))

class WorkoutSession(SQLModel, table=True):
    """One performed instance of a WorkoutDay. Its exercises point back to it via Exercise.session_id."""
    id: int | None = Field(default=None, primary_key=True)
    client_id: str = Field(unique=True) # Generated by the browser so offline saves can be replayed idempotently
    user_id: int = Field(foreign_key='user.id', index=True)
    day_id: int | None = Field(default=None, foreign_key='workoutday.id')
    day_name: str # Copied so history survives renaming or deleting the day
    cycle: int
    week: int
    date: datetime
